// Package dropbox implements the Dropbox plugin for shared links.
//
// Links (www.dropbox.com, dropbox.com, dl.dropbox.com,
// dl.dropboxusercontent.com, db.tt short links):
//
//	/s/<id>/<name>               legacy shared file
//	/scl/fi/<id>/<name>?rlkey=…  shared file
//	/sh/<id>/<key>               legacy shared folder
//	/scl/fo/<id>/<key>?rlkey=…   shared folder
//
// Files are downloaded from the link with dl=1 (other parameters such as
// rlkey are kept); Resolve probes it with HEAD for name and size.
//
// Folders: by default (folder_mode "auto") a session with an account
// (kind apikey with an access token, or kind oauth) lists the folder through
// the API (POST /2/files/list_folder with shared_link, recursive, paged with
// list_folder/continue) and downloads each file with
// /2/sharing/get_shared_link_file, keeping the structure in RelPath.
// Without an account the whole folder is downloaded as one zip generated by
// Dropbox (dl=1 on the folder link; not resumable). folder_mode "zip" or
// "api" forces one of the two.
//
// Limits: links that exceed their traffic allowance are disabled by Dropbox
// for a while (per link, so Quota{ScopeFile}: rotating the IP does not help).
//
// Options ([hosters.dropbox.options]):
//
//	folder_mode   auto | zip | api (default auto)
//	api_base      default https://api.dropboxapi.com
//	content_base  default https://content.dropboxapi.com
//	web_base      replaces scheme://host of shared links (tests only)
